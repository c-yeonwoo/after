/**
 * Exercise real local Supabase Edge Functions against the local Toss HTTP mock.
 * Run with `node scripts/mock-toss-payments.mjs` and
 * `npx supabase functions serve --env-file supabase/functions/.env.mock.local`.
 * This does not use or modify the hosted Supabase project.
 */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createClient } from "@supabase/supabase-js";

const status = execFileSync("npx", ["supabase", "status", "-o", "env"], {
  encoding: "utf8",
});
function localValue(name) {
  const match = status.match(new RegExp(`^${name}="?([^"\\n]+)"?$`, "m"));
  if (!match) throw new Error(`${name} unavailable: start local Supabase first`);
  return match[1];
}

const apiUrl = localValue("API_URL");
const anonKey = localValue("ANON_KEY");
const serviceKey = localValue("SERVICE_ROLE_KEY");
const userClient = createClient(apiUrl, anonKey);
const adminClient = createClient(apiUrl, serviceKey);
function localSql(sql) {
  return execFileSync(
    "psql",
    ["-h", "127.0.0.1", "-p", "55322", "-U", "postgres", "-d", "postgres", "-Atq", "-c", sql],
    {
      encoding: "utf8",
      env: { ...process.env, PGPASSWORD: "postgres" },
    },
  ).trim();
}

const { data: login, error: loginError } = await userClient.auth.signInWithPassword({
  email: "m4@verify.local",
  password: "eclipse-e2e-2026",
});
if (loginError || !login.session) {
  throw new Error("Local E2E user unavailable. Run `bun scripts/e2e-seed.mjs` first.");
}
const accessToken = login.session.access_token;

async function edge(name, body) {
  const response = await fetch(`${apiUrl}/functions/v1/${name}`, {
    method: "POST",
    headers: {
      apikey: anonKey,
      Authorization: `Bearer ${accessToken}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify(body),
  });
  return { status: response.status, body: await response.json() };
}

const originalFlag = localSql("select payments_enabled from app_settings where id = true") === "t";
const createdOrders = [];

try {
  localSql("update app_settings set payments_enabled = true where id = true");

  const { data: order, error: orderError } = await userClient.rpc("create_ticket_order", {
    p_quantity: 3,
    p_kind: "meeting",
  });
  if (orderError) throw orderError;
  createdOrders.push(order.order_id);
  assert.equal(order.payment_required, true);
  assert.equal(order.amount, 85000);

  const paymentKey = `mock_${order.order_id}`;
  const confirm = await edge("confirm-ticket-payment", {
    orderId: order.order_id,
    paymentKey,
    amount: order.amount,
  });
  assert.equal(confirm.status, 200, JSON.stringify(confirm.body));
  assert.equal(confirm.body.tickets.length, 3);

  const repeated = await edge("confirm-ticket-payment", {
    orderId: order.order_id,
    paymentKey,
    amount: order.amount,
  });
  assert.equal(repeated.status, 200, JSON.stringify(repeated.body));
  assert.equal(repeated.body.tickets.length, 3);

  const { data: issued, error: ticketError } = await adminClient
    .from("tickets")
    .select("price_krw,state")
    .in(
      "payment_id",
      [1, 2, 3].map((i) => `${order.order_id}#${i}`),
    );
  if (ticketError) throw ticketError;
  assert.equal(
    issued.reduce((sum, t) => sum + t.price_krw, 0),
    85000,
  );

  const canceled = await edge("cancel-ticket-payment", { orderId: order.order_id });
  assert.equal(canceled.status, 200, JSON.stringify(canceled.body));
  assert.equal(canceled.body.canceled, true);
  const canceledAgain = await edge("cancel-ticket-payment", { orderId: order.order_id });
  assert.equal(canceledAgain.status, 200, JSON.stringify(canceledAgain.body));

  const { data: finalOrder, error: finalError } = await adminClient
    .from("ticket_orders")
    .select("state,payment_key,canceled_at")
    .eq("order_id", order.order_id)
    .single();
  if (finalError) throw finalError;
  assert.equal(finalOrder.state, "canceled");
  assert.equal(finalOrder.payment_key, paymentKey);
  assert.ok(finalOrder.canceled_at);

  const { data: finalTickets, error: finalTicketError } = await adminClient
    .from("tickets")
    .select("state,refund_locked")
    .in(
      "payment_id",
      [1, 2, 3].map((i) => `${order.order_id}#${i}`),
    );
  if (finalTicketError) throw finalTicketError;
  assert.ok(finalTickets.every((t) => t.state === "refunded" && !t.refund_locked));

  process.stdout.write("PASS: local HTTP confirm, retry, ticket issue, cancel and retry\n");
} finally {
  localSql(`update app_settings set payments_enabled = ${originalFlag} where id = true`);
  // Test order IDs are generated by the server and constrained to this exact
  // form before they enter the cleanup SQL.
  for (const orderId of createdOrders) {
    if (!/^ticket_[a-f0-9]{32}$/.test(orderId)) continue;
    const sql = `
      begin;
      delete from events where props->>'order_id' = '${orderId}'
        or props->>'ticket_id' in (
          select id::text from tickets
          where left(payment_id, length('${orderId}') + 1) = '${orderId}#'
        );
      delete from tickets
       where left(payment_id, length('${orderId}') + 1) = '${orderId}#';
      delete from ticket_orders where order_id = '${orderId}';
      commit;`;
    localSql(sql);
  }
}

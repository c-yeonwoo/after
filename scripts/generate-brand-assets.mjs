/** Deterministic exports of the user-approved logo. No image/model API calls. */
import { readFile, writeFile, copyFile, mkdir } from "node:fs/promises";
import { createServer } from "node:http";
import { fileURLToPath } from "node:url";
import { dirname, resolve, sep, extname } from "node:path";
import { execFileSync } from "node:child_process";
import { chromium } from "playwright";
import { format, resolveConfig } from "prettier";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const geometry = JSON.parse(await readFile(resolve(root, "brand/after-logo.json"), "utf8"));
const paths = (part) => part.paths.map((d) => `<path d="${d}"/>`).join("");
const drawing = (part, color) =>
  `<g fill="none" stroke="${color}" stroke-width="${geometry.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${paths(part)}</g>`;
const svg = (width, height, content, viewBox = `0 0 ${width} ${height}`) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${viewBox}" role="img" aria-label="애프터"><title>애프터</title>${content}</svg>\n`;
const wordmark = (color) => svg(325, 114, drawing(geometry.wordmark, color));
const symbol = (color) => svg(104, 110, drawing(geometry.symbol, color));
const icon = (rounded = false) =>
  `<rect width="1024" height="1024" ${rounded ? 'rx="232"' : ""} fill="${geometry.paper}"/><g transform="translate(192 174) scale(6.2)">${drawing(geometry.symbol, geometry.ink)}</g>`;

await mkdir(resolve(root, "public/brand"), { recursive: true });
const geometryPath = resolve(root, "src/lib/brandLogo.ts");
await writeFile(
  geometryPath,
  await format(
    `// Generated by scripts/generate-brand-assets.mjs from brand/after-logo.json.\nexport const BRAND_LOGO = ${JSON.stringify(geometry, null, 2)} as const;\n`,
    { ...(await resolveConfig(geometryPath)), filepath: geometryPath },
  ),
);
for (const [name, content] of [
  ["after-wordmark.svg", wordmark(geometry.ink)],
  ["after-wordmark-white.svg", wordmark("#FFFFFF")],
  ["after-symbol.svg", symbol(geometry.ink)],
]) {
  await writeFile(resolve(root, "brand", name), content);
  await writeFile(resolve(root, "public/brand", name), content);
}
await writeFile(resolve(root, "brand/app-icon-ios.svg"), svg(1024, 1024, icon()));
await writeFile(resolve(root, "public/favicon.svg"), svg(64, 64, icon(true), "0 0 1024 1024"));
await writeFile(
  resolve(root, "brand/splash.svg"),
  svg(
    2732,
    2732,
    `<rect width="2732" height="2732" fill="${geometry.background}"/><g transform="translate(826 1177) scale(3.32)">${drawing(geometry.wordmark, geometry.ink)}</g>`,
  ),
);

// Serve only the OG source, generated vectors and public fonts. Never serve .env.
const server = createServer(async (request, response) => {
  try {
    const path = decodeURIComponent(new URL(request.url, "http://localhost").pathname);
    const file = resolve(root, "." + path);
    const allowed =
      ["brand/og-image.html", "brand/after-wordmark.svg", "brand/after-symbol.svg"].some(
        (name) => file === resolve(root, name),
      ) || file.startsWith(resolve(root, "public/fonts/wanted-sans") + sep);
    if (!allowed || path.split("/").some((segment) => segment.startsWith(".")))
      throw new Error("not found");
    const type = {
      ".html": "text/html; charset=utf-8",
      ".svg": "image/svg+xml",
      ".css": "text/css",
      ".woff2": "font/woff2",
    }[extname(file)];
    const content = await readFile(file);
    response.writeHead(200, { "Content-Type": type || "application/octet-stream" });
    response.end(content);
  } catch {
    response.writeHead(404);
    response.end();
  }
});
await new Promise((done) => server.listen(0, "127.0.0.1", done));
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  const rasterize = async (source, width, height, destination) => {
    await page.setViewportSize({ width, height });
    await page.setContent(
      `<html><head><style>html,body{margin:0;width:100%;height:100%}svg{display:block}</style></head><body>${source}</body></html>`,
    );
    await page.screenshot({ path: resolve(root, destination), omitBackground: true });
  };
  await rasterize(svg(1024, 1024, icon()), 1024, 1024, "brand/app-store-1024.png");
  await rasterize(svg(512, 512, icon(true), "0 0 1024 1024"), 512, 512, "public/icon-512.png");
  await rasterize(
    await readFile(resolve(root, "brand/splash.svg"), "utf8"),
    2732,
    2732,
    "ios/App/App/Assets.xcassets/Splash.imageset/splash-2732x2732.png",
  );
  await rasterize(svg(1024, 1024, icon(true)), 1024, 1024, "brand/social-profile-1024.png");
  execFileSync("python3", [
    "-c",
    `from PIL import Image\nfrom pathlib import Path\nr=Path(__import__('sys').argv[1])\np=r/'brand/app-store-1024.png'\nim=Image.open(p).convert('RGB');im.save(p)\nim.resize((180,180),Image.Resampling.LANCZOS).save(r/'public/apple-touch-icon.png')\nImage.open(r/'public/icon-512.png').save(r/'public/favicon.ico',sizes=[(16,16),(32,32),(48,48),(64,64)])`,
    root,
  ]);
  await copyFile(
    resolve(root, "brand/app-store-1024.png"),
    resolve(root, "ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png"),
  );
  for (const suffix of ["-1", "-2"])
    await copyFile(
      resolve(root, "ios/App/App/Assets.xcassets/Splash.imageset/splash-2732x2732.png"),
      resolve(root, `ios/App/App/Assets.xcassets/Splash.imageset/splash-2732x2732${suffix}.png`),
    );
  await page.setViewportSize({ width: 1200, height: 630 });
  await page.goto(`http://127.0.0.1:${server.address().port}/brand/og-image.html`);
  await page.evaluate(async () => {
    await document.fonts.ready;
    await Promise.all([...document.images].map((image) => image.decode()));
  });
  await page.screenshot({ path: resolve(root, "public/og-image.png") });
  console.log(
    "Approved logo assets generated: app geometry, SVG, favicon, iOS, splash, OG and social profile.",
  );
} finally {
  await browser?.close();
  await new Promise((done) => server.close(done));
}
